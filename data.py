# 8인 이상 가구는 7인 가구 기준 + (가구원 수 - 7) × 추가금
EXTRA_PER_PERSON = {
    2024: 896_625,
    2025: 923_623,
}


def get_median_income(year: int, household_size: int) -> int:
    """가구원 수에 해당하는 기준중위소득(월) 반환. 8인 이상도 자동 계산."""
    table = MEDIAN_INCOME[year]
    if household_size <= 7:
        return table[household_size]
    extra = EXTRA_PER_PERSON[year] * (household_size - 7)
    return table[7] + extra


