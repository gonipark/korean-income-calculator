def find_applicable_programs(percent: float) -> list:
    """주어진 % 이하 기준에 해당하는 제도들을 모두 반환."""
    result = []
    for threshold, programs in sorted(PROGRAMS_BY_PERCENT.items()):
        if percent <= threshold:
            for name, desc in programs:
                result.append((threshold, name, desc))
    return result


